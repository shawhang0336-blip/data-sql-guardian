"""ProdAgent 微内核（机制层）：机制在内，策略在外。

本包只包含与业务域完全解耦的六大内核核心模块：
1. Plan (`plan.py`)：静态只读工作流蓝图（`PlanNode` / `PlanEdge` / `WorkflowPlan`）；
2. Bus (`bus.py`)：事前门禁裁决（`check` / `adjudicate`）+ 全生命周期事后广播（`fire` / `subscribe`）；
3. EventLog (`event_log.py`)：带 SHA-256 哈希链的只追加事件账本与状态折叠引擎；
4. Interrupt (`interrupt.py`)：一等人工中断指令与幂等回答协议；
5. Run (`run.py`)：运行实例控制面（`RunContext` / `ChannelSpec` / `BudgetGuard` / `CancellationToken` / `RunRegistry` / 全生命周期原语）；
6. Scheduler (`scheduler.py`)：真 BSP 波次调度引擎（`Send` 动态扇出 + `Goto` + `Interrupt` + `execute_wave`）。
"""

